#!/usr/bin/env python3
"""Generate the migration for the Builders Club offers that Habbo names only in furnidata.

Habbo's furnidata marks a furni `bc` and names its Builders Club offer in `bcofferid`; the infostand's copy and the Builders Club
search place it by that offer (AIR WIN63-202610151745-318700621, com/sulake/habbo/ui/widget/infostand/InfoStandWidget.as:557-564,
com/sulake/habbo/catalog/HabboCatalog.as:1927-1950). Many of those offers are on no page of the BUILDERS_CLUB index, so a catalogue
built from the index alone (migration 91) has no offer for them. This puts every such single-furni offer on one hidden, enabled
Builders Club page.

Input: the capture of hhus' BUILDERS_CLUB pages (the `bc_pages` list, or a file holding it) and Habbo's furnidata_json of the same day.
An offer id shared by several furni is a bundle and is left out: a Builders Club placement places one furni.

Usage: build-builders-club-furnidata-offers.py CAPTURE.json FURNIDATA.json OUT.sql
"""
import argparse
import json

HIDDEN_PAGE_ID = 2100000100


def sql(value):
    if isinstance(value, int):
        return str(value)
    return "'" + str(value).replace('\\', '\\\\').replace("'", "''") + "'"


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument('capture')
    parser.add_argument('furnidata')
    parser.add_argument('out')
    args = parser.parse_args()

    capture = json.load(open(args.capture, encoding='utf-8'))
    pages = capture['bc_pages'] if isinstance(capture, dict) else capture
    furnidata = json.load(open(args.furnidata, encoding='utf-8'))
    on_pages = {offer['OfferId'] for page in pages for offer in page['page']['Offers']}

    named = {}
    for section, product_type in (('roomitemtypes', 's'), ('wallitemtypes', 'i')):
        for entry in furnidata[section]['furnitype']:
            offer_id = entry.get('bcofferid', -1)
            if entry.get('bc') and offer_id is not None and offer_id > 0 and offer_id not in on_pages:
                named.setdefault(offer_id, []).append((entry['classname'], product_type))

    offers = sorted((offer_id, furni[0][0], furni[0][1]) for offer_id, furni in named.items() if len(furni) == 1)
    bundles = sorted(offer_id for offer_id, furni in named.items() if len(furni) > 1)

    out = [f"""-- Builders Club offers that Habbo's furnidata names (bc, bcofferid) but no page of the BUILDERS_CLUB index shows: the infostand's
-- copy and the Builders Club search place them by that offer (AIR WIN63-202610151745-318700621, ui/widget/infostand/InfoStandWidget.as:557-564,
-- catalog/HabboCatalog.as:1927-1950). Migration 91 built the tree from the index only, so these furni (the coloured bc_block_0 blocks among
-- them) had no Builders Club offer. Generated by scripts/build-builders-club-furnidata-offers.py from the hhus capture and Habbo's
-- furnidata_json of 2026-10-17: {len(offers)} offers on one hidden, enabled Builders Club page ({len(bundles)} bundle left out).
-- An offer reuses our offer of Habbo's id when it sells the same furni once, else one with the furni's key that does, else it is
-- created with Habbo's id when that id is free. Idempotent: reruns end in the same state.

CREATE TEMPORARY TABLE `bc_furnidata_offers_92` (
    `habbo_id` INT NOT NULL PRIMARY KEY, `classname` VARCHAR(100) NOT NULL, `product_type` CHAR(1) NOT NULL,
    `furniture_id` INT UNSIGNED NULL, `offer_id` INT NULL, `position` INT NOT NULL, KEY (`classname`)
);
"""]

    for start in range(0, len(offers), 500):
        part = offers[start:start + 500]
        out.append('INSERT INTO `bc_furnidata_offers_92` (`habbo_id`, `classname`, `product_type`, `position`) VALUES\n' +
                   ',\n'.join(f'    ({sql(o)}, {sql(c)}, {sql(t)}, {start + i})' for i, (o, c, t) in enumerate(part)) + ';\n')

    out.append(f"""-- Each furni by classname: the row that carries its furnidata, else the first. furniture.item_name has no index, so the
-- pick per classname goes through a keyed table instead of one furniture scan per offer.
CREATE TEMPORARY TABLE `bc_furniture_92` (
    `item_name` VARCHAR(100) CHARACTER SET utf8mb4 COLLATE utf8mb4_unicode_ci NOT NULL, `type` CHAR(1) NOT NULL, `id` INT UNSIGNED NOT NULL,
    PRIMARY KEY (`item_name`, `type`)
);
INSERT INTO `bc_furniture_92` (`item_name`, `type`, `id`)
SELECT `item_name`, `type`, `id` FROM (
    SELECT `item_name`, `type`, `id`, ROW_NUMBER() OVER (PARTITION BY `item_name`, `type` ORDER BY `has_furnidata` DESC, `id`) AS `pick`
    FROM `furniture`
) AS `candidate`
WHERE `pick` = 1;
UPDATE `bc_furnidata_offers_92` AS `offer`
LEFT JOIN `bc_furniture_92` AS `furni` ON `furni`.`item_name` = `offer`.`classname` AND `furni`.`type` = `offer`.`product_type`
SET `offer`.`furniture_id` = `furni`.`id`;
DROP TEMPORARY TABLE `bc_furniture_92`;

-- Habbo's offer id when our offer of that id sells the same furni once.
UPDATE `bc_furnidata_offers_92` AS `offer`
SET `offer`.`offer_id` = `offer`.`habbo_id`
WHERE `offer`.`furniture_id` IS NOT NULL
    AND (SELECT COUNT(*) FROM `catalog_offer_products` AS `product` WHERE `product`.`offer_id` = `offer`.`habbo_id`) = 1
    AND EXISTS (SELECT 1 FROM `catalog_offer_products` AS `product`
        WHERE `product`.`offer_id` = `offer`.`habbo_id` AND `product`.`product_type` = 'furni'
            AND `product`.`furniture_id` = `offer`.`furniture_id` AND `product`.`amount` = 1);

-- Otherwise an offer with the furni's key selling it once (also what an earlier run created).
UPDATE `bc_furnidata_offers_92` AS `offer`
SET `offer`.`offer_id` = (
    SELECT MIN(`existing`.`id`) FROM `catalog_offers` AS `existing`
    INNER JOIN `catalog_offer_products` AS `product` ON `product`.`offer_id` = `existing`.`id`
    WHERE `existing`.`localization_key` = `offer`.`classname` AND `product`.`product_type` = 'furni'
        AND `product`.`furniture_id` = `offer`.`furniture_id` AND `product`.`amount` = 1
        AND (SELECT COUNT(*) FROM `catalog_offer_products` AS `other` WHERE `other`.`offer_id` = `existing`.`id`) = 1)
WHERE `offer`.`offer_id` IS NULL AND `offer`.`furniture_id` IS NOT NULL;

-- Otherwise a new offer: with Habbo's id when it is free, else the next id.
INSERT INTO `catalog_offers` (`id`, `localization_key`, `cost_credits`, `cost_points`, `points_type`, `club_level`, `bulk_purchase`, `enabled`, `preview_image`)
SELECT IF(EXISTS (SELECT 1 FROM `catalog_offers` AS `taken` WHERE `taken`.`id` = `offer`.`habbo_id`), NULL, `offer`.`habbo_id`),
    `offer`.`classname`, 0, 0, 0, 0, 0, 1, ''
FROM `bc_furnidata_offers_92` AS `offer`
WHERE `offer`.`offer_id` IS NULL AND `offer`.`furniture_id` IS NOT NULL
ORDER BY `offer`.`habbo_id`;

-- The new offers, the only ones of their key without a product, get their furni.
INSERT IGNORE INTO `catalog_offer_products` (`offer_id`, `position`, `product_type`, `furniture_id`, `amount`, `extra_param`)
SELECT `created`.`id`, 0, 'furni', `offer`.`furniture_id`, 1, ''
FROM `bc_furnidata_offers_92` AS `offer`
INNER JOIN `catalog_offers` AS `created` ON `created`.`localization_key` = `offer`.`classname`
WHERE `offer`.`offer_id` IS NULL AND `offer`.`furniture_id` IS NOT NULL
    AND NOT EXISTS (SELECT 1 FROM `catalog_offer_products` AS `product` WHERE `product`.`offer_id` = `created`.`id`);

UPDATE `bc_furnidata_offers_92` AS `offer`
SET `offer`.`offer_id` = (
    SELECT MIN(`existing`.`id`) FROM `catalog_offers` AS `existing`
    INNER JOIN `catalog_offer_products` AS `product` ON `product`.`offer_id` = `existing`.`id`
    WHERE `existing`.`localization_key` = `offer`.`classname` AND `product`.`product_type` = 'furni'
        AND `product`.`furniture_id` = `offer`.`furniture_id` AND `product`.`amount` = 1)
WHERE `offer`.`offer_id` IS NULL AND `offer`.`furniture_id` IS NOT NULL;

-- One hidden root page holds them: enabled, so a placement by offer finds it, and left out of the visible tree.
INSERT INTO `catalog_pages` (`id`, `parent_id`, `caption`, `icon`, `position`, `link`, `layout`, `catalog_mode`, `visible`, `enabled`, `required_club_level`)
VALUES ({HIDDEN_PAGE_ID}, NULL, 'Builders Club furni', 1, 99, 'bc_furnidata_offers', 'default_3x3', 'BUILDERS_CLUB', 0, 1, 0)
ON DUPLICATE KEY UPDATE `parent_id` = NULL, `caption` = VALUES(`caption`), `icon` = VALUES(`icon`), `position` = VALUES(`position`),
    `link` = VALUES(`link`), `layout` = VALUES(`layout`), `catalog_mode` = 'BUILDERS_CLUB', `visible` = 0, `enabled` = 1, `required_club_level` = 0;

DELETE FROM `catalog_page_offers` WHERE `page_id` = {HIDDEN_PAGE_ID};
INSERT IGNORE INTO `catalog_page_offers` (`page_id`, `offer_id`, `position`)
SELECT {HIDDEN_PAGE_ID}, `offer_id`, `position` FROM `bc_furnidata_offers_92` WHERE `offer_id` IS NOT NULL;

DROP TEMPORARY TABLE `bc_furnidata_offers_92`;
""")

    open(args.out, 'w', encoding='utf-8', newline='\n').write('\n'.join(out))
    print(f'{len(offers)} offers, bundles left out: {bundles}')


if __name__ == '__main__':
    main()
